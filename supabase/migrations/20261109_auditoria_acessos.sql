CREATE TABLE IF NOT EXISTS public.auditoria_sessoes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id uuid NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  sessao_id uuid NOT NULL UNIQUE,
  inicio_em timestamptz NOT NULL DEFAULT now(),
  ultima_atividade_em timestamptz NOT NULL DEFAULT now(),
  ultimo_modulo text,
  ultima_pagina text,
  dispositivo text,
  eventos integer NOT NULL DEFAULT 1 CHECK (eventos > 0)
);
CREATE INDEX IF NOT EXISTS auditoria_sessoes_usuario_data_idx ON public.auditoria_sessoes (usuario_id, ultima_atividade_em DESC);
CREATE INDEX IF NOT EXISTS auditoria_sessoes_data_idx ON public.auditoria_sessoes (inicio_em DESC);
ALTER TABLE public.auditoria_sessoes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.auditoria_sessoes FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.auditoria_sessoes_id_seq FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.auditoria_registrar_atividade(
  p_sessao_id uuid, p_modulo text DEFAULT NULL, p_pagina text DEFAULT NULL,
  p_dispositivo text DEFAULT NULL
) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_usuario uuid := auth.uid();
BEGIN
  IF v_usuario IS NULL OR p_sessao_id IS NULL THEN
    RAISE EXCEPTION 'Sessao nao autenticada';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.usuarios WHERE id = v_usuario AND ativo IS DISTINCT FROM false) THEN
    RAISE EXCEPTION 'Usuario sem perfil ativo';
  END IF;
  IF EXISTS (SELECT 1 FROM public.auditoria_sessoes WHERE sessao_id = p_sessao_id AND usuario_id <> v_usuario) THEN
    RAISE EXCEPTION 'Sessao nao pertence ao usuario';
  END IF;
  INSERT INTO public.auditoria_sessoes(usuario_id,sessao_id,ultimo_modulo,ultima_pagina,dispositivo)
  VALUES (v_usuario,p_sessao_id,left(p_modulo,80),left(p_pagina,80),left(p_dispositivo,30))
  ON CONFLICT (sessao_id) DO UPDATE SET
    ultima_atividade_em = now(),
    ultimo_modulo = COALESCE(EXCLUDED.ultimo_modulo, auditoria_sessoes.ultimo_modulo),
    ultima_pagina = COALESCE(EXCLUDED.ultima_pagina, auditoria_sessoes.ultima_pagina),
    dispositivo = COALESCE(EXCLUDED.dispositivo, auditoria_sessoes.dispositivo),
    eventos = LEAST(auditoria_sessoes.eventos+1,2147483647)
  WHERE auditoria_sessoes.usuario_id = v_usuario;
END;
$$;
REVOKE ALL ON FUNCTION public.auditoria_registrar_atividade(uuid,text,text,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.auditoria_registrar_atividade(uuid,text,text,text) TO authenticated;

CREATE OR REPLACE FUNCTION public.auditoria_consultar_acessos()
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_resultado jsonb;
BEGIN
  IF auth.uid() IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.usuarios WHERE id = auth.uid() AND papel = 'admin' AND ativo IS DISTINCT FROM false
  ) THEN
    RAISE EXCEPTION 'Acesso restrito ao Administrador do Sistema';
  END IF;
  SELECT jsonb_build_object(
    'usuarios', COALESCE((
      SELECT jsonb_agg(to_jsonb(u) ORDER BY u.nome) FROM (
        SELECT id,nome,email,papel,ativo,codigo_vendedor FROM public.usuarios
      ) u
    ), '[]'::jsonb),
    'resumo',COALESCE((
      SELECT jsonb_agg(to_jsonb(t)) FROM (
        SELECT u.id AS usuario_id, max(s.ultima_atividade_em) AS ultimo_acesso,
          count(s.id) AS sessoes_total,
          count(s.id) FILTER (WHERE s.inicio_em >= now()-interval '7 days') AS sessoes_7d,
          count(s.id) FILTER (WHERE s.inicio_em >= now()-interval '30 days') AS sessoes_30d
        FROM public.usuarios u LEFT JOIN public.auditoria_sessoes s ON s.usuario_id=u.id
        GROUP BY u.id
      ) t
    ),'[]'::jsonb),
    'sessoes',COALESCE((
      SELECT jsonb_agg(to_jsonb(s) ORDER BY s.inicio_em DESC) FROM (
        SELECT usuario_id,inicio_em,ultima_atividade_em,ultimo_modulo,ultima_pagina,dispositivo,eventos
        FROM public.auditoria_sessoes ORDER BY inicio_em DESC LIMIT 3000
      ) s
    ),'[]'::jsonb)
  ) INTO v_resultado;
  RETURN v_resultado;
END;
$$;
REVOKE ALL ON FUNCTION public.auditoria_consultar_acessos() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.auditoria_consultar_acessos() TO authenticated;

COMMENT ON TABLE public.auditoria_sessoes IS 'Auditoria operacional por sessao. Sem GPS, IP ou geolocalizacao. Definir politica de retencao.';
